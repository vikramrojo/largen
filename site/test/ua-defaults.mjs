/* Regenerate genai/ua-defaults.json.
 *
 * explain_slot reports what a slot reverts TO, and that value comes from the
 * user-agent stylesheet — which is not an input to anything and differs between
 * engines. The honest options were to omit it, to assert it from memory, or to
 * measure it and say what was measured. This measures it, using largen's own
 * probe, and records the engine alongside so a caller can weigh the answer.
 *
 * That the slot reverts at all is derived from the caller's stylesheets and needs
 * none of this. Only the illustration does.
 *
 *   node site/test/ua-defaults.mjs        # rewrites genai/ua-defaults.json
 */
import { writeFileSync } from 'node:fs'
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import { buildProbe } from '../../genai/probe.js'
import { paintMap } from '../../genai/slots.js'
import { readFileSync } from 'node:fs'

const run = promisify(execFile)
const CHROME = process.env.CHROME ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'
const root = new URL('../../', import.meta.url).pathname
const out = new URL('../../genai/ua-defaults.json', import.meta.url).pathname

/* The properties the paint rule drives — read from the rule, so adding a slot
   extends this table without editing it. */
const properties = [...paintMap(readFileSync(root + 'src/paint.css', 'utf8')).slotToProperty.values()]

/* Elements whose UA defaults a component author actually meets. */
const ELEMENTS = [
  'a', 'button', 'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'p', 'ul', 'ol', 'li',
  'table', 'th', 'td', 'input', 'code', 'pre', 'kbd', 'blockquote', 'hr',
  'fieldset', 'legend', 'select', 'textarea', 'strong', 'small', 'div', 'span',
  'summary', 'dt', 'dd', 'figure', 'mark',
]

const inTable = new Set(['th', 'td'])
const body = ELEMENTS.map((e) => {
  if (e === 'table') return '<table id="e-table"><tbody><tr><th id="e-th">t</th><td id="e-td">d</td></tr></tbody></table>'
  if (inTable.has(e) || e === 'li') return ''
  return `<${e} id="e-${e}" href="#">x</${e}>`
}).join('')

const html = `<!doctype html><html><head><meta charset="utf-8"></head><body>${body}<ul><li id="e-li">x</li></ul></body></html>`

const { stdout: version } = await run(CHROME, ['--version'])
const probe = buildProbe({
  kind: 'computed', html, selectors: ELEMENTS.map((e) => `#e-${e}`), properties, timeout: 5000,
})
writeFileSync('/tmp/largen-ua-probe.html', probe)

const { stdout } = await run(CHROME, [
  '--headless', '--disable-gpu', '--virtual-time-budget=6000', '--dump-dom',
  'file:///tmp/largen-ua-probe.html',
], { timeout: 60_000, maxBuffer: 32 * 1024 * 1024 })

const unescape = (s) => s
  .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"')
  .replace(/&#39;/g, "'").replace(/&amp;/g, '&')

const m = stdout.match(/<pre id="json"[^>]*>([\s\S]*?)<\/pre>/)
if (!m || !m[1].trim()) throw new Error('the probe produced no results')
const rows = JSON.parse(unescape(m[1])).rows

const missing = rows.filter((r) => r.missing).map((r) => r.selector)
if (missing.length) throw new Error(`these elements never rendered: ${missing.join(', ')}`)

const elements = {}
for (const r of rows) elements[r.selector.replace('#e-', '')] = r.values

writeFileSync(out, JSON.stringify({
  $comment:
    'User-agent stylesheet defaults, MEASURED not asserted — generated by a largen ' +
    'probe (genai/probe.js) against the engine named below and recorded verbatim. ' +
    'These are engine-specific: another browser may differ, and this file says which ' +
    'one it came from precisely so a caller can weigh that. Regenerate with ' +
    'site/test/ua-defaults.mjs. Used only to illustrate what a slot reverts TO; the ' +
    'fact THAT it reverts is derived from the stylesheets and needs none of this.',
  engine: version.trim(),
  measured: new Date().toISOString().slice(0, 10),
  properties,
  elements,
}, null, 1) + '\n')

console.log(`\n  genai/ua-defaults.json — ${Object.keys(elements).length} elements × ${properties.length} properties`)
console.log(`  measured on ${version.trim()}\n`)
